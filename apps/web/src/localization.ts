export function resolveLocale(languages: readonly string[]): Locale {
  for (const language of languages) {
    const code = language.toLowerCase().split("-")[0];
    if (code === "zh") return "zh";
    if (code === "es") return "es";
    if (code === "en") return "en";
  }
  // This deployment is the Chinese edition: Chinese is the fallback when
  // the browser states no supported preference.
  return "zh";
}

export function translate(
  locale: Locale,
  key: MessageKey,
  values: Record<string, string | number> = {}
): string {
  const template = (locale === "zh" ? chinese : locale === "es" ? spanish : english)[key];
  return template.replace(/\{(\w+)\}/g, (_, name: string) => String(values[name] ?? `{${name}}`));
}

export const locale = resolveLocale(
  typeof navigator === "undefined" ? [] : navigator.languages.length ? navigator.languages : [navigator.language]
);
export const t = (key: MessageKey, values?: Record<string, string | number>) =>
  translate(locale, key, values);
